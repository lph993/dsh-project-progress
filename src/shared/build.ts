/**
 * ## 批次 69 的用途
 *
 * **进度自动回写（①+②）**：把"进度回写"从**靠模型自觉**变成机制保证。
 *
 * 起因是用户的质疑（2026-10-11 原文）：「为什么不能在运行中自动处理进度呢，别人用难道也要
 * 手动告诉你需要刷新树了，不太合理吧」。实测证实了这个缺陷：树上的 32 个叶节点**全部卡在
 * 0.50–0.70、完成数为 0**，整体比例长期冻在 0.649 —— 不是"没有机制"，而是既有边界逻辑
 * （`session/boundary.ts`）只做 `pending → running`，**从不知道这一回合有没有回写过**，
 * 所以永远推不到收尾；而写在系统提示词里的纪律，模型（本会话就是）会整轮忽略。
 *
 * 本批新增：
 * - `session/report-candidate.ts`（纯函数）：按「本回合变动的文件」×「节点自己声明的 `refs`」
 *   挑出**有证据**该被重新评估的候选节点，并渲染成一条可执行的提醒；
 * - `BoundNode` 增补 `refs`（边界层原先不知道节点负责哪些路径，无法做上述判断）；
 * - 证据采集：第二个 `tools/pre-execute` 钩子记「写工具碰过哪些文件」与
 *   「本回合调过 `pm_report`/`pm_finish` 没有」——**不查 git**，因为 git 分不出"哪次会话碰的"；
 * - 边界提醒改为两种合并：候选提醒（有证据）+ 原有的"仍在进行中"提醒，且**催促有上限**
 *   （连续 3 次不回写就收手，避免提醒退化成白噪音）。
 *
 * **不越界的一点**：本功能**绝不产生进度数字**。`session/prompt.ts` 已定下前提——
 * 宿主只能做有证据的推断（`pending → running`），真实数字只有干活的模型知道。
 * 所以自动化只作用在"逼模型汇报"这一环，不作用在"替模型决定汇报什么"。
 */
/**
 * ## 批次 70 的用途
 *
 * **自动发现**（用户质疑的落点）：「这些是你刚加的，为什么需要我提醒你才行，
 * 插件却没起作用」。查下来批次 69 的机制有两处硬伤，本批修掉：
 *
 * 1. **候选池建错了前提**：批次 69 取的是"该会话**订阅过**的节点"，而实际干活的人
 *    **从不订阅** ⇒ 提醒永不触发（AIG 那棵树因此冻了 8 小时）。改为取**整个项目**的节点。
 * 2. **只有"更新已有节点"，没有"树上缺节点"**：做完一个功能却没人建节点时，插件毫无察觉。
 *    新增**盲区检测**：本回合改动的文件若**不属于任何节点的 refs**，就在回合收尾时提醒
 *    建节点（`pm_add`，并把 refs 指向这些路径，下次才不再是盲区）。判据全是事实
 *    （文件确实变了 + 树里读得到），不含推测、不产生数字。
 *
 * 与批次 69 同一底线：**绝不产生进度数字**。宿主只负责"发现"与"催"，数字仍由模型给。
 */

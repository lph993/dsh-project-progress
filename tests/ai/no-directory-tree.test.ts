/**
 * **建树不得以目录为骨架**（用户原话，2026-10-17 落档于 `docs/开发须知.md` §0.0）：
 *
 * > "不能按目录…目录只是好分类，代表功能具有严重局限性。"
 *
 * 这条原则此前**只存在于会话中，已经丢失过一次**（用户："因为没有落档只存于会话中造成了丢失"）。
 * 所以这里不只把它写进文档，还用测试钉住**可核对的部分**：
 *
 * 1. 提示词必须**显式禁止**把目录当树结构（否则模型看到按目录排列的骨架就会照抄）；
 * 2. 整形逻辑必须**消掉包装层**（子节点提一级），而不是把目录层降级保留。
 *
 * 为什么钉"提示词文本"而不是只钉行为：`AI_TREE_SYSTEM_PROMPT` 是模型唯一的规则来源，
 * 它被改窄或被"优化"掉时**不会有任何运行时报错** —— 只能靠测试。
 */

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { AI_TREE_SYSTEM_PROMPT } from '../../src/ai/prompt.ts';

describe('提示词必须禁止"按目录建树"', () => {
  const text = AI_TREE_SYSTEM_PROMPT;

  it('明确写出"不许把目录当成树的结构"', () => {
    assert.match(text, /不许把目录当成树的结构/, '这条原则必须出现在提示词里（用户反复提过）');
  });

  it('引用用户原话"目录只是好分类"（让人知道这条从哪来）', () => {
    assert.match(text, /目录只是好分类/, '出处要写在提示词里，否则下一个人会当成我的个人偏好删掉');
  });

  it('点名禁止"包装层"：refs 只有一条目录、子节点全在其下', () => {
    assert.match(text, /包装层/, '包装层是这次真机的病灶（「Web 服务端」），必须被点名');
  });

  it('给出"能不能回答这块要做什么"这条判据', () => {
    assert.match(text, /这块要做什么/, '判据要可操作，不只是口号');
  });

  it('举了该出现与不该出现的名字（示例比抽象规则管用）', () => {
    assert.match(text, /体检报告查询与打印|GaussDB|跨平台宿主切换/, '要有"好"的例子');
    assert.match(text, /Web 服务端|Controllers|Scripts|Modules/, '要有"坏"的例子');
  });

  it('保留原有的"不要照抄目录名"（两层防线）', () => {
    assert.match(text, /不要照抄目录名/, '原来那条不许被新规则替换掉，而是叠加');
  });
});